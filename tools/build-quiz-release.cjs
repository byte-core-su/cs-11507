'use strict';

// Only formatting and local identifier mangling; no answer/validation changes.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { minify } = require('terser');
const root = path.resolve(__dirname, '..');
const sourceRoot = path.join(root, '.maintenance', 'quiz-sources');
const stateFile = path.join(sourceRoot, 'release-state.json');
const targets = [
  'terms/115-1/infolife.html',
  'terms/115-2/security.html',
  'shared/quiz-focus-guard.js'
];
const banner = '/* Quiz release: generated by tools/build-quiz-release.cjs. */';
// Git may normalize Windows line endings; that is not a manual content edit.
const digest = text => crypto.createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');
const mode = process.argv[2];

async function minifyScript(source) {
  const result = await minify(source, {
    compress: false,
    mangle: { toplevel: false, eval: false },
    sourceMap: false,
    format: { ascii_only: true, comments: false, inline_script: true }
  });
  if (!result.code) throw new Error('Empty JavaScript output');
  return `${banner}\n${result.code}`;
}

async function release(relative, original) {
  if (relative.endsWith('.js')) return `${await minifyScript(original)}\n`;
  const pattern = /(<script\b([^>]*)>)([\s\S]*?)(<\/script\s*>)/gi;
  let output = '', cursor = 0, count = 0;
  for (const match of original.matchAll(pattern)) {
    const [whole, open, attributes, code, close] = match;
    output += original.slice(cursor, match.index);
    if (/\bsrc\s*=/i.test(attributes) || !code.trim()) output += whole;
    else {
      output += `${open}\n${await minifyScript(code)}\n${close}`;
      count++;
    }
    cursor = match.index + whole.length;
  }
  if (!count) throw new Error(`No inline scripts found: ${relative}`);
  return output + original.slice(cursor);
}

async function main() {
  if (!['--capture', '--build', '--check'].includes(mode)) {
    throw new Error('Use --capture once, then edit .maintenance/quiz-sources and use --build or --check.');
  }
  if (mode === '--capture') {
    // Never recapture generated output or overwrite an existing editable source.
    for (const relative of targets) {
      const source = path.join(sourceRoot, relative);
      const published = fs.readFileSync(path.join(root, relative), 'utf8');
      if (fs.existsSync(source) || published.includes(banner)) {
        throw new Error(`Capture refused; source already exists or output is generated: ${relative}`);
      }
    }
    const state = {};
    for (const relative of targets) {
      const original = fs.readFileSync(path.join(root, relative), 'utf8');
      const source = path.join(sourceRoot, relative);
      fs.mkdirSync(path.dirname(source), { recursive: true });
      fs.copyFileSync(path.join(root, relative), source, fs.constants.COPYFILE_EXCL);
      state[relative] = { outputHash: digest(original) };
    }
    fs.writeFileSync(stateFile, `${JSON.stringify(state, null, 2)}\n`);
    console.log('Editable sources captured locally; no website files changed.');
    return;
  }
  if (!fs.existsSync(stateFile)) throw new Error('Local editable sources are missing. Do not capture minified output.');
  const state = JSON.parse(fs.readFileSync(stateFile, 'utf8'));
  const pending = [];
  // Validate every file before writing anything; protect unrelated manual edits.
  for (const relative of targets) {
    const original = fs.readFileSync(path.join(sourceRoot, relative), 'utf8');
    const current = fs.readFileSync(path.join(root, relative), 'utf8');
    const output = await release(relative, original);
    if (mode === '--check' && digest(current) !== digest(output)) throw new Error(`Out-of-date release: ${relative}`);
    if (mode === '--build' && digest(current) !== state[relative]?.outputHash && digest(current) !== digest(output)) {
      throw new Error(`Published file was manually changed; merge changes into the local source first: ${relative}`);
    }
    pending.push({ relative, output, original });
  }
  if (mode === '--build') {
    for (const { relative, output, original } of pending) {
      fs.writeFileSync(path.join(root, relative), output);
      state[relative] = { sourceHash: digest(original), outputHash: digest(output) };
    }
    fs.writeFileSync(stateFile, `${JSON.stringify(state, null, 2)}\n`);
  }
  console.log(mode === '--check' ? 'All quiz releases match their local sources.' : 'Built both quiz pages and their focus guard; no source maps generated.');
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
